const filterWad = specials => specials.filter(entry => entry.value <= 255);

const createSpecialSet = (lines, things, sectors, wadLines = lines) => ({
    lines: [...lines],
    things: [...things],
    sectors: [...sectors],
    linesWad: filterWad(wadLines),
    thingsWad: filterWad(things),
    sectorsWad: filterWad(sectors),
});

const SPECIAL_PORT_MAP = {
    hexen_wad: {
        family: 'hexen',
        wad: true,
    },
    hexen_udmf: {
        family: 'hexen',
        wad: false,
    },
    zdoom_hexen_wad: {
        family: 'zdoom',
        wad: true,
    },
    zdoom_udmf: {
        family: 'zdoom',
        wad: false,
    },
    gzdoom_hexen_wad: {
        family: 'gzdoom',
        wad: true,
    },
    gzdoom_udmf: {
        family: 'gzdoom',
        wad: false,
    },
};

const SPECIALS_BY_PORT = {
    hexen: createSpecialSet(
        HEXEN_LINE_SPECIALS_UDMF,
        HEXEN_THING_SPECIALS,
        HEXEN_SECTOR_SPECIALS,
        HEXEN_LINE_SPECIALS,
    ),
    zdoom: createSpecialSet(
        ZDOOM_LINE_SPECIALS,
        ZDOOM_THING_SPECIALS,
        ZDOOM_SECTOR_SPECIALS,
    ),
    gzdoom: createSpecialSet(
        GZDOOM_LINE_SPECIALS,
        GZDOOM_THING_SPECIALS,
        GZDOOM_SECTOR_SPECIALS,
    ),

    sectorProperties: SECTOR_SPECIAL_BITWISE_PROPERTIES,

    getSpecials(port, type) {
        const mapping = SPECIAL_PORT_MAP[port];

        if (mapping === undefined) {
            return [];
        }

        return this[mapping.family][mapping.wad ? `${type}Wad` : type];
    },
};

for (const family of ['hexen', 'zdoom', 'gzdoom']) {
    for (const specials of Object.values(SPECIALS_BY_PORT[family])) {
        specials.sort((a, b) => a.value - b.value);
    }
}

export default SPECIALS_BY_PORT;
